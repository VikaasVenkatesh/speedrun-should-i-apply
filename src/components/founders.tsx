"use client";
import { useEffect, useState } from "react";
import { AnimatePresence, motion } from "motion/react";
import { Search, Users, FlaskConical, MapPin, AlertTriangle } from "lucide-react";
import type { Candidate, Job } from "@/lib/schemas";
import { Header, Spinner, VerdictBadge, formatComp, workplaceLabel } from "./ui";
import { Footer } from "./app";

export function Founders() {
  const [jobs, setJobs] = useState<Job[] | null>(null);
  const [source, setSource] = useState<string | null>(null);
  const [q, setQ] = useState("");
  const [query, setQuery] = useState("");
  const [selected, setSelected] = useState<Job | null>(null);
  const [cands, setCands] = useState<Candidate[] | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    const ctrl = new AbortController();
    fetch(`/api/jobs?scope=speedrun${query ? `&q=${encodeURIComponent(query)}` : "&fn=engineering,product,design"}`, { signal: ctrl.signal })
      .then((r) => r.json())
      .then((d) => {
        setJobs(d.jobs ?? []);
        setSource(d.source);
      })
      .catch(() => {});
    return () => ctrl.abort();
  }, [query]);

  async function pick(j: Job) {
    setSelected(j);
    setCands(null);
    setError(null);
    setLoading(true);
    if (window.innerWidth < 768) setTimeout(() => document.getElementById("shortlist")?.scrollIntoView({ behavior: "smooth" }), 50);
    try {
      const r = await fetch("/api/founders", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ job_id: j.id }) });
      const d = await r.json();
      if (!r.ok) throw new Error(d.error ?? "Failed");
      setCands(d.candidates);
    } catch (e) {
      setError(e instanceof Error ? e.message : "Failed");
    } finally {
      setLoading(false);
    }
  }

  return (
    <>
      <Header />
      <main className="mx-auto w-full max-w-5xl flex-1 px-4 py-10">
        <p className="text-sm font-medium text-accent">The other side of the table</p>
        <h1 className="mt-1 text-3xl font-semibold tracking-tight sm:text-4xl">Who should this founder talk to first?</h1>
        <p className="mt-2 max-w-2xl text-ink-2">
          The same fit engine, pointed at candidates. Pick an open speedrun role and get a ranked shortlist with reasons and blockers.
        </p>
        <p className="mt-3 inline-flex items-center gap-1.5 rounded-full bg-stretch-bg px-3 py-1 text-xs font-medium text-stretch">
          <FlaskConical className="size-3.5" /> Candidates are synthetic demo profiles generated by Claude, not real people.
        </p>

        <div className="mt-8 grid gap-6 md:grid-cols-[320px_1fr]">
          <div>
            <form
              onSubmit={(e) => {
                e.preventDefault();
                if (q.trim() === query) return;
                setJobs(null);
                setQuery(q.trim());
              }}
              className="flex items-center gap-2 rounded-full bg-surface px-3 py-2 ring-1 ring-line focus-within:ring-2 focus-within:ring-ink"
            >
              <Search className="size-4 text-ink-3" />
              <input value={q} onChange={(e) => setQ(e.target.value)} placeholder="Search speedrun roles" className="w-full bg-transparent text-sm outline-none" />
            </form>
            <div className="mt-2 flex flex-wrap items-center gap-1.5 px-1 text-xs text-ink-3">
              <span>{source === "sample" ? "Sample data" : "Live from the speedrun portfolio"}</span>
              {["product engineer", "founding engineer", "designer"].map((t) => (
                <button
                  key={t}
                  onClick={() => {
                    if (t === query) return;
                    setQ(t);
                    setJobs(null);
                    setQuery(t);
                  }}
                  className={`rounded-full px-2 py-0.5 ring-1 transition ${query === t ? "bg-ink text-bg ring-ink" : "ring-line hover:text-ink"}`}
                >
                  {t}
                </button>
              ))}
            </div>
            <ul className="mt-2 max-h-[60vh] space-y-1.5 overflow-y-auto pr-1">
              {!jobs && Array.from({ length: 6 }).map((_, i) => <li key={i} className="shimmer h-14 rounded-xl" />)}
              {jobs?.slice(0, 40).map((j) => (
                <li key={j.id}>
                  <button
                    onClick={() => pick(j)}
                    className={`w-full rounded-xl px-3 py-2.5 text-left transition ${
                      selected?.id === j.id ? "bg-ink text-bg" : "bg-surface ring-1 ring-line hover:ring-ink-3"
                    }`}
                  >
                    <p className="truncate text-sm font-medium">{j.title}</p>
                    <p className={`truncate text-xs ${selected?.id === j.id ? "text-bg/70" : "text-ink-3"}`}>
                      {j.company} · {j.location || "—"}
                    </p>
                  </button>
                </li>
              ))}
              {jobs && !jobs.length && <li className="px-1 text-sm text-ink-3">No roles found.</li>}
            </ul>
          </div>

          <div id="shortlist" className="min-w-0 scroll-mt-20">
            {!selected && (
              <div className="grid h-full min-h-72 place-items-center rounded-3xl border border-dashed border-line p-8 text-center">
                <div>
                  <Users className="mx-auto size-8 text-ink-3" />
                  <p className="mt-3 font-medium">Pick a role to see a ranked shortlist</p>
                  <p className="mt-1 text-sm text-ink-3">5 to 8 demo candidates, scored against the real posting.</p>
                </div>
              </div>
            )}
            {selected && (
              <div>
                <div className="rounded-2xl bg-surface p-4 ring-1 ring-line">
                  <p className="font-semibold">{selected.title}</p>
                  <p className="mt-0.5 flex flex-wrap items-center gap-x-2 text-sm text-ink-3">
                    <span className="text-ink-2">{selected.company}</span>
                    <span className="inline-flex items-center gap-0.5">
                      <MapPin className="size-3.5" /> {selected.location}
                    </span>
                    {workplaceLabel(selected.workplace_type, selected.remote) && <span>· {workplaceLabel(selected.workplace_type, selected.remote)}</span>}
                    {formatComp(selected.comp_min, selected.comp_max, selected.comp_currency) && (
                      <span>· {formatComp(selected.comp_min, selected.comp_max, selected.comp_currency)}</span>
                    )}
                  </p>
                </div>
                {loading && (
                  <div className="mt-4 space-y-3">
                    <p className="flex items-center gap-2 text-sm text-ink-3">
                      <Spinner /> Reading the posting and ranking candidates…
                    </p>
                    {Array.from({ length: 4 }).map((_, i) => (
                      <div key={i} className="shimmer h-28 rounded-2xl" />
                    ))}
                  </div>
                )}
                {error && <p className="mt-4 rounded-xl bg-danger-bg px-3 py-2 text-sm text-danger">{error}</p>}
                <ol className="mt-4 space-y-3">
                  <AnimatePresence>
                    {cands?.map((c, i) => (
                      <motion.li
                        key={c.name}
                        initial={{ opacity: 0, y: 8 }}
                        animate={{ opacity: 1, y: 0 }}
                        transition={{ delay: i * 0.06 }}
                        className="rounded-2xl bg-surface p-4 ring-1 ring-line"
                      >
                        <div className="flex items-start gap-3">
                          <span className="grid size-8 shrink-0 place-items-center rounded-full bg-surface-2 text-sm font-semibold tabular-nums">{i + 1}</span>
                          <div className="min-w-0 flex-1">
                            <div className="flex items-start justify-between gap-2">
                              <div className="min-w-0">
                                <p className="font-semibold">
                                  {c.name} <span className="ml-1 rounded bg-surface-2 px-1.5 py-0.5 align-middle text-[10px] font-medium uppercase tracking-wide text-ink-3">Demo</span>
                                </p>
                                <p className="text-sm text-ink-3">
                                  {c.headline} · {c.location} · {c.years_experience} yrs
                                </p>
                              </div>
                              <div className="flex shrink-0 flex-col items-end gap-1">
                                <VerdictBadge verdict={c.verdict} size="sm" />
                                <span className="text-[11px] tabular-nums text-ink-3">{c.score}/100</span>
                              </div>
                            </div>
                            <ul className="mt-2 space-y-1 text-sm text-ink-2">
                              {c.fit_reasons.map((r, j) => (
                                <li key={j} className="flex gap-2">
                                  <span className="mt-2 size-1 shrink-0 rounded-full bg-ink-3" />
                                  {r}
                                </li>
                              ))}
                            </ul>
                            <p className="mt-2 flex items-start gap-1.5 text-xs text-stretch">
                              <AlertTriangle className="mt-0.5 size-3.5 shrink-0" /> {c.risk}
                            </p>
                          </div>
                        </div>
                      </motion.li>
                    ))}
                  </AnimatePresence>
                </ol>
              </div>
            )}
          </div>
        </div>
      </main>
      <Footer />
    </>
  );
}
